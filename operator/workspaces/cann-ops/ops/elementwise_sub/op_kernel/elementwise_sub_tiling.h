// [MODIFY] 分核逻辑（可执行文件与 .so 共用同一份，避免两份漂移）
//
// 关键约束（2026-10-28 真机实测）：一次 launch 的 blockNum **不得超过物理核数**。
// 之前把 1M 摊成 256 个 block 直接慢成 0.652×（8.36us → 12.82us）：多出的 block 在核上排队，
// 每个核都要重新启动 + 建 TPipe/队列，等于白付一遍启动开销。所以 blockNum ≤ coreNum 是硬约束。
//
//   大 shape（N > 2 × MAX_TILE_LENGTH）：Core Shrink + 均分 + 8 元素对齐
//     used   = clamp(N / MIN_PER_CORE_LENGTH, 1, coreNum)     # 开几个核
//     per    = ceil(N / used)                                  # 每核目标长度
//     tile   = alignUp(per, 8) ≤ MAX_TILE_LENGTH，blockNum = ceil(N / tile) ≤ coreNum
//     ⇒ 常规规模下每核正好一个 full tile（除尾块），核间完全并行、无跨 tile 串行；
//       N 超过 coreNum × MAX_TILE_LENGTH 时 tile 封顶，每核多轮（blockNum = coreNum）
//
//   小 shape（N ≤ 8192）：单核，tileLength = 512（N 更小时 = alignUp(N,8)），tileNum = ceil(N/512)。
//     单核是刻意的：小 shape 的定点开销吃在核启动 + TPipe/队列构造上，开 48 核只放大这部分；
//     tile 取 512 是 v1 沿用的实测值，32 / 128 等更小块未做过对照，不写进默认路径。
static inline uint64_t AlignUp8(uint64_t v)
{
    return (v + VEC_ALIGN_LENGTH - 1) / VEC_ALIGN_LENGTH * VEC_ALIGN_LENGTH;
}

